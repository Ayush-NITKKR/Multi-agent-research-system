import os
import uuid
import logging
from typing import Dict, List, Any, Optional
from datetime import datetime, timezone

from fastapi import FastAPI, HTTPException, BackgroundTasks, status
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field
from dotenv import load_dotenv

load_dotenv()

from research_adapter import execute_research_workflow, parse_sources, parse_critic_feedback

# Setup logging
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s"
)
logger = logging.getLogger("python_api")

app = FastAPI(
    title="ResearchAI Python Microservice",
    description="Internal AI microservice wrapping the multi-agent research pipeline",
    version="1.0.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],  # Internal service, restrictable via firewall/container network
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# In-memory store for tracking jobs
JOBS_STORE: Dict[str, Dict[str, Any]] = {}

class SourceItem(BaseModel):
    title: str = ""
    url: str = ""
    snippet: str = ""
    domain: str = ""

class CriticFeedback(BaseModel):
    score: float = 0.0
    criteria: Optional[Dict[str, float]] = None
    critical_issues: List[str] = []
    issues: List[str] = []
    missing_information: List[str] = []
    recommendations: List[str] = []
    verdict: str = "NEEDS REVISION"
    next_action: str = "revise"
    strengths: List[str] = []
    raw_feedback: str = ""

class ResearchRequest(BaseModel):
    topic: str = Field(..., min_length=3, max_length=500, description="The research topic to investigate")
    job_id: Optional[str] = Field(None, description="Unique job identifier generated by caller")
    max_revisions: Optional[int] = Field(2, ge=0, le=2, description="Maximum revision attempts if critic requests it")
    enable_revisions: Optional[bool] = Field(True, description="Whether to run revision loop")
    async_execution: Optional[bool] = Field(False, description="Run in background and poll for result")

class ResearchResponse(BaseModel):
    job_id: str
    status: str
    topic: str
    report: Optional[str] = None
    sources: Optional[List[SourceItem]] = None
    critic_feedback: Optional[CriticFeedback] = None
    revisions: Optional[List[Dict[str, Any]]] = None
    execution_metadata: Optional[Dict[str, Any]] = None
    requires_user_rerun: bool = False
    error: Optional[str] = None

class JobStatusResponse(BaseModel):
    job_id: str
    status: str
    topic: str
    error: Optional[str] = None
    requires_user_rerun: bool = False
    has_report: bool = False
    created_at: str

